#pragma once

#include <stdint.h>

// Narrow 5x7 digits for the clock, so "14:37" fits on 32 columns with room to spare
// (the 8x8 font makes it ~31 px wide). Hand-drawn for this project.
// Stored by column, ready for fb: one byte per column, bit y = row y (y = 0 is the top),
// so digits use rows 0..6 and leave the bottom row free.
#define DIGIT_WIDTH 5

static const uint8_t font_digits[10][DIGIT_WIDTH] = {
    { 0x3E, 0x41, 0x41, 0x41, 0x3E },  // 0
    { 0x00, 0x42, 0x7F, 0x40, 0x00 },  // 1
    { 0x42, 0x61, 0x51, 0x49, 0x46 },  // 2
    { 0x22, 0x41, 0x49, 0x49, 0x36 },  // 3
    { 0x18, 0x14, 0x12, 0x7F, 0x10 },  // 4
    { 0x27, 0x45, 0x45, 0x45, 0x39 },  // 5
    { 0x3C, 0x4A, 0x49, 0x49, 0x30 },  // 6
    { 0x01, 0x71, 0x09, 0x05, 0x03 },  // 7
    { 0x36, 0x49, 0x49, 0x49, 0x36 },  // 8
    { 0x06, 0x49, 0x49, 0x29, 0x1E },  // 9
};

#define COLON_COLUMN 0x14  // rows 2 and 4
#define DOT_COLUMN   0x40  // row 6
